"""Create clearly labeled synthetic bootstraps and report sample counts."""
import csv
from pathlib import Path
path=Path('data/dataset.csv'); rows=list(csv.DictReader(path.open(encoding='utf-8-sig',newline='')))
topics=['home','market','school','travel','festivals']
patterns={
 'Hubballi-Dharwad': [('ಏನ್ ಮಾಡ್ತೀರಾ?','ಏನು ಮಾಡುತ್ತೀರಾ?'),('ನಾನು ಬರ್ತೀನಿ.','ನಾನು ಬರುತ್ತೇನೆ.'),('ನೀವು ಮನೆಗೆ ಬರ್ತೀರಾ?','ನೀವು ಮನೆಗೆ ಬರುತ್ತೀರಾ?'),('ಅದು ಎಲ್ಲಿ ಇದೆ?','ಅದು ಎಲ್ಲಿ ಇದೆ?'),('ಯಾಕ ಬಂದಿರಿ?','ಯಾಕೆ ಬಂದಿರಿ?')],
 'Mangaluru': [('ಎಂತ ಬೇಕು?','ಏನು ಬೇಕು?'),('ನಾನು ಮನೆಗೆ ಹೋಗ್ತೀನಿ.','ನಾನು ಮನೆಗೆ ಹೋಗುತ್ತೇನೆ.'),('ನೀವು ಶಾಲೆಗೆ ಬರ್ತೀರಾ?','ನೀವು ಶಾಲೆಗೆ ಬರುತ್ತೀರಾ?'),('ನೀರು ಉಂಟು.','ನೀರು ಇದೆ.'),('ಅಂಗಡಿಯಲ್ಲಿ ಏನು ಇದೆ?','ಅಂಗಡಿಯಲ್ಲಿ ಏನು ಇದೆ?')],
 'Uttara Kannada': [('ಹೆಂಗ ಇದ್ದೀರಿ?','ಹೇಗೆ ಇದ್ದೀರಿ?'),('ನಾನು ಬರ್ತೀನಿ.','ನಾನು ಬರುತ್ತೇನೆ.'),('ನೀವು ಊಟಕ್ಕೆ ಬರ್ತೀರಾ?','ನೀವು ಊಟಕ್ಕೆ ಬರುತ್ತೀರಾ?'),('ಅದು ಎಲ್ಲಿ ಸಿಗುತ್ತೆ?','ಅದು ಎಲ್ಲಿ ಸಿಗುತ್ತದೆ?'),('ಯಾಕ ತಡ ಆಯಿತು?','ಯಾಕೆ ತಡವಾಯಿತು?')],
}
towns={'Hubballi-Dharwad':'Hubballi','Mangaluru':'Mangaluru','Uttara Kannada':'Sirsi'}
if not any(r.get('synthetic')=='true' for r in rows):
    for dialect,examples in patterns.items():
        for i in range(20):
            source,target=examples[i%len(examples)]
            # Kannada numerals distinguish generated test variants; they remain synthetic metadata rows.
            numeral=str(i+1).translate(str.maketrans('0123456789','೦೧೨೩೪೫೬೭೮೯'))
            rows.append({'dialect':dialect,'town':towns[dialect],'dialect_text':source.rstrip('.?!')+' '+numeral+'?','standard_text':target.rstrip('.?!')+' '+numeral+'?','age_band':'','sentence_id':f'synth-{dialect[:2]}-{i+1:03d}','topic':topics[i%5],'speaker_id':'','synthetic':'true','verified_by':'','source':'synthetic','audio_file':''})
    with path.open('w',encoding='utf-8',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=rows[0].keys());writer.writeheader();writer.writerows(rows)
print('Official examples:',sum(r.get('source')=='official_example' for r in rows))
print('Synthetic bootstrap examples:',sum(r.get('synthetic')=='true' for r in rows))
print('No real speaker data are generated by this tool.')
